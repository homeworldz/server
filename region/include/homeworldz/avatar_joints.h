// Each joint and the joint above it, from the same `avatar_skeleton.xml` the
// rest positions come from. Generated, for the reason given above.
//
// This exists because a *joint position override is relative to the parent*:
// the viewer writes it to the joint's local transform and accumulates world
// position down this hierarchy. Converting an imported rig's positions into
// overrides therefore needs the hierarchy the viewer will accumulate through,
// and it is not the source rig's. Character Creator runs Pelvis -> Waist ->
// Spine01 -> Spine02 where this runs mPelvis -> mSpine1 -> mSpine2 -> mTorso;
// the spine joints Bento inserts are bound by nothing and keep the skeleton's
// own offsets, so a body measured against the source's parents came apart from
// the chest up while its legs, whose chains do correspond, stayed correct.
struct JointParent {
    std::string_view joint;
    std::string_view parent;  // empty for mPelvis, which is the root
};

