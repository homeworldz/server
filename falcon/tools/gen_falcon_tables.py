"""Writes falcon/src/lsl_index.inc from the function index (falcon/index), so
Falcon's compiler takes every signature and constant value from the index
rather than from a hand-kept list.

    python -I falcon/tools/gen_falcon_tables.py

The generated file is committed, so building Falcon needs no Python. It holds
the whole compatibility surface; which functions and events actually compile
is still decided in compiler.cpp (implemented_functions, implemented_events),
because a function the region does not answer must fail to compile rather
than compile and do nothing.

Types are one character each: v void, i integer, f float, s string, k key,
V vector, r rotation, l list.

Float constants are left out until Falcon has a float type.
"""
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
FALCON = os.path.dirname(HERE)
INDEX = os.path.join(FALCON, "index")
OUT = os.path.join(FALCON, "src", "lsl_index.inc")

TYPE_CODES = {"void": "v", "integer": "i", "float": "f", "string": "s", "key": "k", "vector": "V",
              "rotation": "r", "list": "l"}


def load(name):
    with open(os.path.join(INDEX, name), encoding="utf-8") as handle:
        return json.load(handle)


def codes(params, where):
    try:
        return "".join(TYPE_CODES[p["type"]] for p in params)
    except KeyError as error:
        raise ValueError("%s: no type code for %s" % (where, error))


def int32(text, where):
    try:
        value = int(text, 0)
    except ValueError:
        raise ValueError("%s: cannot read integer %r" % (where, text))
    value &= 0xFFFFFFFF
    return value - 0x100000000 if value >= 0x80000000 else value


def cpp_integer(value):
    # the most negative int32 has no literal of its own in C++
    return "(-2147483647 - 1)" if value == -2147483648 else str(value)


def string_bytes(text):
    """The definitions write a newline as \\n and some characters as \\u{FDD0}."""
    text = re.sub(r"\\u\{([0-9A-Fa-f]+)\}", lambda m: chr(int(m.group(1), 16)), text)
    text = text.replace("\\n", "\n").replace("\\t", "\t").replace('\\"', '"').replace("\\\\", "\\")
    return text.encode("utf-8")


def cpp_string(data):
    out = []
    for byte in data:
        char = chr(byte)
        if char in '"\\':
            out.append("\\" + char)
        elif 0x20 <= byte < 0x7F:
            out.append(char)
        else:
            # octal, always three digits, so a following digit cannot join the escape
            out.append("\\%03o" % byte)
    return '"' + "".join(out) + '"'


def components(text, where):
    parts = [p.strip() for p in text.strip().lstrip("<").rstrip(">").split(",")]
    if len(parts) not in (3, 4):
        raise ValueError("%s: cannot read %r" % (where, text))
    return [float(p) for p in parts]


def main():
    functions = load("functions.json")
    events = load("events.json")
    constants = load("constants.json")

    lines = [
        "// Generated by falcon/tools/gen_falcon_tables.py from falcon/index; do not edit.",
        "//",
        "// Every function, event and constant of the compatibility surface (Second",
        "// Life LSL plus the Halcyon/InWorldz extensions). Types are one character",
        "// each: v void, i integer, f float, s string, k key, V vector, r rotation,",
        "// l list.",
        "",
        "struct IndexFunction {",
        "    const char* name;",
        "    char result;",
        "    const char* params;",
        "};",
        "struct IndexEvent {",
        "    const char* name;",
        "    const char* params;",
        "};",
        "struct IndexInteger {",
        "    const char* name;",
        "    std::int32_t value;",
        "};",
        "struct IndexString {",
        "    const char* name;",
        "    std::string_view value;",
        "};",
        "struct IndexVector {",
        "    const char* name;",
        "    int size;  // 3 for a vector, 4 for a rotation",
        "    double components[4];",
        "};",
        "",
        "constexpr IndexFunction index_functions[] = {",
    ]
    for entry in sorted(functions, key=lambda f: f["name"]):
        lines.append('    {"%s", \'%s\', "%s"},' % (entry["name"], TYPE_CODES[entry["returns"]],
                                                  codes(entry["params"], entry["name"])))
    lines += ["};", "", "constexpr IndexEvent index_events[] = {"]
    for entry in sorted(events, key=lambda e: e["name"]):
        lines.append('    {"%s", "%s"},' % (entry["name"], codes(entry["params"], entry["name"])))
    lines += ["};", ""]

    integers, strings, vectors, floats = [], [], [], 0
    for entry in sorted(constants, key=lambda c: c["name"]):
        name, kind, value = entry["name"], entry["type"], str(entry["value"])
        if kind == "integer":
            integers.append('    {"%s", %s},' % (name, cpp_integer(int32(value, name))))
        elif kind in ("string", "key"):
            data = string_bytes(value)
            strings.append('    {"%s", {%s, %d}},' % (name, cpp_string(data), len(data)))
        elif kind in ("vector", "rotation"):
            parts = components(value, name)
            padded = parts + [0.0] * (4 - len(parts))
            vectors.append('    {"%s", %d, {%s}},' % (name, len(parts), ", ".join(repr(p) for p in padded)))
        elif kind == "float":
            floats += 1
        else:
            raise ValueError("%s: constant type %r" % (name, kind))
    lines += ["constexpr IndexInteger index_integers[] = {"] + integers + ["};", ""]
    lines += ["constexpr IndexString index_strings[] = {"] + strings + ["};", ""]
    lines += ["constexpr IndexVector index_vectors[] = {"] + vectors + ["};"]

    with open(OUT, "w", encoding="utf-8", newline="\n") as handle:
        handle.write("\n".join(lines) + "\n")
    print(json.dumps({"functions": len(functions), "events": len(events), "integers": len(integers),
                      "strings": len(strings), "vectors": len(vectors), "floats_left_out": floats}))


if __name__ == "__main__":
    try:
        main()
    except (OSError, ValueError) as error:
        print("gen_falcon_tables: %s" % error, file=sys.stderr)
        sys.exit(1)
